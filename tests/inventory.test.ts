import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { availableUnits, validStayDates } from '../lib/inventory';

const db = new DatabaseSync(':memory:');
db.exec(`CREATE TABLE availability(room_id TEXT,night TEXT,units_open INTEGER,closed INTEGER);
  CREATE TABLE booking_requests(id TEXT,room_id TEXT,check_in TEXT,check_out TEXT,rooms INTEGER,status TEXT);`);
const room = { id: 'room', units: 2 };
const reserve = db.prepare('INSERT INTO booking_requests VALUES(?,?,?,?,?,?)');
const override = db.prepare('INSERT INTO availability VALUES(?,?,?,?)');
assert.equal(validStayDates('2026-02-30', '2026-03-03'), false);
assert.equal(validStayDates('invalid', '2026-03-03'), false);
assert.equal(validStayDates('2026-11-02', '2026-11-02'), false);
assert.equal(validStayDates('2026-11-01', '2028-11-02'), false);
assert.equal(availableUnits(db, room, '2026-11-01', '2026-11-04'), 2);
reserve.run('first', room.id, '2026-11-01', '2026-11-03', 1, 'confirmed');
reserve.run('second', room.id, '2026-11-02', '2026-11-04', 1, 'checked_in');
reserve.run('cancelled', room.id, '2026-11-01', '2026-11-05', 2, 'cancelled');
reserve.run('pending', room.id, '2026-11-01', '2026-11-05', 2, 'pending');
assert.equal(availableUnits(db, room, '2026-11-01', '2026-11-04'), 0);
assert.equal(availableUnits(db, room, '2026-11-03', '2026-11-04'), 1);
assert.equal(availableUnits(db, room, '2026-11-04', '2026-11-05'), 2);
assert.equal(availableUnits(db, room, '2026-11-01', '2026-11-04', 'first'), 1);
override.run(room.id, '2026-11-04', 1, 0);
assert.equal(availableUnits(db, room, '2026-11-04', '2026-11-05'), 1);
override.run(room.id, '2026-11-05', 2, 1);
assert.equal(availableUnits(db, room, '2026-11-04', '2026-11-06'), 0);
override.run(room.id, '2026-11-06', 99, 0);
assert.equal(availableUnits(db, room, '2026-11-06', '2026-11-07'), 2);
db.close();
console.log('PASS: nightly inventory, overlapping stays, checkout boundary, closures, overrides and invalid dates');
